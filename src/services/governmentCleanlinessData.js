function getDistanceKm(lat1, lon1, lat2, lon2) {
  if (lat1 == null || lon1 == null || lat2 == null || lon2 == null) return null;
  const R = 6371;
  const phi1 = (lat1 * Math.PI) / 180;
  const phi2 = (lat2 * Math.PI) / 180;
  const deltaPhi = ((lat2 - lat1) * Math.PI) / 180;
  const deltaLambda = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(deltaPhi / 2) * Math.sin(deltaPhi / 2) +
    Math.cos(phi1) * Math.cos(phi2) * Math.sin(deltaLambda / 2) * Math.sin(deltaLambda / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export function getCityCleanlinessData(userLocation, userWard = '') {
  const uLat = userLocation?.latitude != null ? parseFloat(userLocation.latitude) : null;
  const uLng = userLocation?.longitude != null ? parseFloat(userLocation.longitude) : null;
  const wardStr = (userWard || '').toLowerCase();

  // 1. Check keyword match with user ward/address text
  if (wardStr) {
    for (const city of GOVERNMENT_CITIES_RANKING) {
      if (city.keywords.some((k) => wardStr.includes(k))) {
        return {
          ...city,
          distanceKm: uLat && uLng ? Math.round(getDistanceKm(uLat, uLng, city.latitude, city.longitude)) : null,
          matchedBy: 'ward_text',
        };
      }
    }
  }

  // 2. Check closest city by GPS coordinates
  if (uLat != null && uLng != null) {
    let closestCity = null;
    let minDistance = Infinity;

    for (const city of GOVERNMENT_CITIES_RANKING) {
      const dist = getDistanceKm(uLat, uLng, city.latitude, city.longitude);
      if (dist < minDistance) {
        minDistance = dist;
        closestCity = city;
      }
    }

    if (closestCity) {
      const isWithinRadius = minDistance <= closestCity.radiusKm + 15;
      return {
        ...closestCity,
        distanceKm: Math.round(minDistance),
        isExactCity: isWithinRadius,
        matchedBy: 'gps_proximity',
      };
    }
  }

  // 3. Default to Greater Noida / Delhi NCR baseline
  return {
    ...GOVERNMENT_CITIES_RANKING[0],
    distanceKm: null,
    matchedBy: 'default',
  };
}

